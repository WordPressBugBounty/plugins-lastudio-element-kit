/**
 * Small shim that replaces the `LaStudioKitThemeBuilder\Modules\LoopBuilder\Classes\Plugin` helpers used by the ported Loop Builder code.
 */
class Plugin {

	/**
	 * @return \Elementor\Plugin
	 */
	public static function elementor() {
		return \Elementor\Plugin::$instance;
	}

	public static function get_assets_url( $path = '' ) {
		return lastudio_kit()->plugin_url( 'includes/modules/loop-builder/assets/' . $path );
	}

	public static function get_assets_path( $path = '' ) {
		return lastudio_kit()->plugin_path( 'includes/modules/loop-builder/assets/' . $path );
	}

	private static function get_responsive_templates_path() {
		return self::get_assets_path( 'css/templates/' );
	}

	/**
	 * Return the URL of a frontend CSS file. When the site uses custom breakpoints the file is
	 * generated by Elementor core from the template stored in `assets/css/templates/`.
	 */
	public static function get_frontend_file_url( $frontend_file_name, $custom_file ) {
		if ( $custom_file ) {
			$template_file_path = self::get_responsive_templates_path() . $frontend_file_name;
			$frontend_file = self::elementor()->frontend->get_frontend_file( $frontend_file_name, 'custom-lakit-', $template_file_path );

			return $frontend_file->get_url();
		}

		return self::get_assets_url( 'css/' . $frontend_file_name );
	}
}
